def get_answer_generation_messages(query: str, details_text: str, history_summary: str = None) -> list[dict]:
    """답변 생성을 위한 최종 메시지 리스트(system/user) 구성"""
    context_section = f"[이전 대화 요약]\n{history_summary}\n\n" if history_summary else ""
    
    system_content = COMMON_SYSTEM_INSTRUCTIONS
    user_content = (
        f"{context_section}"
        f"질문: {query}\n\n"
        f"[제공된 식당 정보]:\n{details_text}\n\n"
        "위 정보를 바탕으로 부드럽고 자연스럽게 답변해 주세요."
    )
    
    return [
        {"role": "system", "content": system_content},
        {"role": "user", "content": user_content}
    ]

def get_condition_extraction_prompt(query: str, current_time: str, history_text: str = None) -> str:
    """검색 조건 추출을 위한 프롬프트 구성"""
    history_section = f"대화 기록:\n{history_text}\n\n" if history_text else ""
    
    return (
        f"현재시각: {current_time}\n\n"
        f"{history_section}"
        f"새 메시지: {query}\n\n"
        "위 대화에서 검색 조건을 JSON으로 추출하세요.\n"
        "[추출 규칙]\n"
        "1. 'region': 언급된 지역명 (예: '판교', '수내')\n"
        "2. 'category': 음식 종류 (한식, 일식, 중식, 양식, 고기, 해산물, 아시안, 분식, 기타 중 선택)\n"
        "3. 'name_query': 문장의 주인공이 되는 특정 식당 이름\n"
        "4. 'menu_query': 구체적인 메뉴 명칭이나 분위기 키워드\n"
        "5. 'open_now', 'parking', 'room': true/false\n"
        "6. 'capacity_min': 숫자 또는 null\n"
        "7. 'requested_count': 요청한 추천 식당 개수 (언급 없으면 null)\n"
        "8. **문맥 유지**: 멀티턴 대화인 경우 이전 맥락을 유지하면서 필터를 업데이트하거나, 새로운 식당 언급 시 초기화하세요.\n\n"
        "JSON만 출력:\n"
        '{"region":null, "category":null, "name_query":null, "menu_query":null, "capacity_min":null, "parking":false, "room":false, "open_now":false, "requested_count":null}'
    )
