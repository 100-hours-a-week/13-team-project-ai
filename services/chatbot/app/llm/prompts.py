def _select_prompt(query: str, history_summary: str | None, details_count: int) -> str:
    """
    질문 유형에 따라 최적의 시스템 프롬프트를 선택한다.

    우선순위:
    1. 특정 식당 1곳 상세 조회   → LOOKUP_PROMPT
    2. 이전 추천 중 조건 필터링  → FILTERED_RECOMMEND_PROMPT
    3. 조건 + 감성 복합 추천     → COMPLEX_RECOMMEND_PROMPT
    4. 감성/분위기 단독 추천     → HYDE_PROMPT
    5. 일반 추천                  → RECOMMEND_PROMPT
    """
    # --- 조건 키워드 ---
    filter_kw  = ["주차", "룸", "영업", "운영", "시간", "메뉴", "전화", "정보", "번호", "위치", "예약", "단체"]
    compare_kw = ["이 중", "이중에", "세곳", "세 곳", "둘 중", "셋 중", "비교", "중에서",
                  "방금", "아까", "그곳", "거기", "모두"]
    subjective = ["분위기", "감성", "조용", "데이트", "소개팅", "부모님", "회식",
                  "가기 좋은", "고급", "품격", "깔끔"]
    facility   = ["룸 있는", "주차 가능", "룸이 있는", "예약 가능", "단체"]

    # 1) 특정 식당 1곳 조회 (details_count가 1이면 우선적으로 상세 조회 모드)
    # 단, 히스토리가 있고 비교/지칭 키워드가 명시적으로 있으면 필터링 모드로 보냄
    if details_count == 1:
        if not history_summary or any(k in query for k in filter_kw) and not any(k in query for k in compare_kw):
            return LOOKUP_PROMPT

    # 2) 이전 추천 목록 내 조건 필터 (히스토리가 있고 비교 지시어가 있거나, 특정 정보 키워드가 있는 경우)
    if history_summary and (any(k in query for k in compare_kw) or any(k in query for k in filter_kw)):
        return FILTERED_RECOMMEND_PROMPT
    
    # 3) 조건 + 감성 복합 추천 (시설 조건과 분위기 조건이 동시에 있음)
    has_facility   = any(k in query for k in facility)
    has_subjective = any(k in query for k in subjective)
    if has_facility and has_subjective:
        return COMPLEX_RECOMMEND_PROMPT

    # 4) 감성/분위기 단독 추천
    if has_subjective:
        return HYDE_PROMPT

    # 5) 기본: 분류 불가 시 일반 추천 프롬프트(RECOMMEND_PROMPT)로 폴백
    return RECOMMEND_PROMPT


